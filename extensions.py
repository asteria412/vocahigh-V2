# =====================================================================
# extensions.py - Flask 확장 모듈 모음
# =====================================================================
# Flask는 기능을 "확장(Extension)"으로 붙여 쓰는 구조야.
# 여기서 확장들을 미리 만들어두고, app에는 나중에 연결해.
# 이렇게 하면 순환 참조(circular import) 문제를 피할 수 있어.
# =====================================================================

from flask_sqlalchemy import SQLAlchemy
from flask_login import LoginManager

# -------------------------------------------------------------------
# SQLAlchemy - 데이터베이스 ORM
# -------------------------------------------------------------------
# ORM: SQL을 직접 쓰지 않고 Python 클래스로 DB를 다루게 해주는 도구
db = SQLAlchemy()

# -------------------------------------------------------------------
# LoginManager - 로그인/로그아웃 관리
# -------------------------------------------------------------------
login_manager = LoginManager()

# 로그인이 필요한 페이지에 접근했을 때 이동할 주소
login_manager.login_view = 'auth.login'

# 로그인이 필요하다는 안내 메시지
login_manager.login_message = '로그인이 필요한 페이지예요.'
login_manager.login_message_category = 'warning'
